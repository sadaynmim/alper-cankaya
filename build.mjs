import fs from 'node:fs';
import path from 'node:path';
const dir='dist'; fs.rmSync(dir,{recursive:true,force:true}); fs.mkdirSync(dir,{recursive:true});
fs.copyFileSync('src/index.html',path.join(dir,'index.html'));
if(fs.existsSync('media')) fs.cpSync('media',path.join(dir,'media'),{recursive:true});
const items=(name)=>fs.existsSync('content/'+name)?fs.readdirSync('content/'+name).filter(x=>x.endsWith('.json')).sort().map(x=>JSON.parse(fs.readFileSync('content/'+name+'/'+x,'utf8'))):[];
const works=items('works').map(w=>({...w,description:{tr:w.description_tr||'',en:w.description_en||'',ar:w.description_ar||'',fr:w.description_fr||''}}));
const gallery=items('gallery');
const bio=JSON.parse(fs.readFileSync('content/bio.json','utf8'));
const news=items('news');
const legacyNews=fs.existsSync('content/news.json')?JSON.parse(fs.readFileSync('content/news.json','utf8')):null;
fs.writeFileSync(path.join(dir,'archive-content.js'),'window.ARCHIVE_CONTENT='+JSON.stringify({works,gallery,bio,news,legacyNews}).replace(/</g,'\u003c')+';');
console.log('Built: '+works.length+' works, '+gallery.length+' photos, '+news.length+' new articles');
